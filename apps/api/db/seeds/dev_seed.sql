-- lines, and directions are verbatim. Directions are split into one step per sentence.
-- Each recipe's source column names the original contributor and source_url points
-- to its myplate.gov page. USDA asks for this citation when reusing them:
--   U.S. Department of Agriculture. MyPlate Kitchen Website. <title>. <source>.
--   Available at MyPlate.gov/MyPlateKitchen.
-- Some contributors are state or university programs rather than federal agencies,
-- so these recipes are not all public domain.
-- Cuisine, methods, and the ingredient matching are ours. Lines with no matching
-- catalog ingredient keep ingredient_id NULL and show in the review queue.

